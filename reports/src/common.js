/** Resolve a localized value: either a plain string/number or { ar, en }. */
function t(v, lang) {
  if (v == null) return "";
  if (typeof v === "object" && !Array.isArray(v) && ("ar" in v || "en" in v)) return v[lang] ?? v.ar ?? v.en ?? "";
  return v;
}

/** Western digits are used in both languages (government document convention). */
function formatNumber(n, lang, opts = {}) {
  if (typeof n !== "number") return t(n, lang);
  return new Intl.NumberFormat(lang === "ar" ? "ar-SA-u-nu-latn" : "en-US", { maximumFractionDigits: 2, ...opts }).format(n);
}

function formatValue(v, col, lang) {
  if (typeof v === "number") {
    if (col?.format === "percent") return formatNumber(v, lang, { style: "percent", maximumFractionDigits: 1 });
    if (col?.format === "currency") return formatNumber(v, lang, { maximumFractionDigits: 2 }) + (lang === "ar" ? " ر.س" : " SAR");
    return formatNumber(v, lang);
  }
  return String(t(v, lang));
}

/** Hijri (Umm al-Qura) + Gregorian date strings. */
function dates(date = new Date(), lang = "ar") {
  const loc = lang === "ar" ? "ar-SA" : "en-GB";
  const hijri = new Intl.DateTimeFormat(`${loc}-u-ca-islamic-umalqura-nu-latn`, { day: "numeric", month: "long", year: "numeric" }).format(date);
  const greg = new Intl.DateTimeFormat(`${loc}-u-ca-gregory-nu-latn`, { day: "numeric", month: "long", year: "numeric" }).format(date);
  const dmy = (cal) => {
    const parts = Object.fromEntries(new Intl.DateTimeFormat(`en-u-ca-${cal}-nu-latn`, { day: "2-digit", month: "2-digit", year: "numeric" })
      .formatToParts(date).map((p) => [p.type, p.value]));
    return `${parts.day}/${parts.month}/${parts.year}`;
  };
  const hijriShort = dmy("islamic-umalqura");
  const gregShort = dmy("gregory");
  const time = new Intl.DateTimeFormat("en-GB", { hour: "2-digit", minute: "2-digit", hour12: false }).format(date);
  // Intl already appends "هـ"/"AH" to Hijri dates.
  return { hijri, greg, hijriShort, gregShort, time, both: `${hijri} — ${greg}`, bothShort: lang === "ar" ? `${hijriShort} هـ | ${gregShort} م` : `${hijriShort} AH | ${gregShort}` };
}

/** Normalises a report spec and resolves everything that depends on language. */
function prepare(spec, opts = {}) {
  const lang = opts.lang || spec.lang || "ar";
  if (!["ar", "en"].includes(lang)) throw new Error(`Unsupported language "${lang}" (use ar or en)`);
  const now = opts.now ? new Date(opts.now) : new Date();
  const cls = CLASSIFICATION[spec.classification || "internal"] || { ar: spec.classification, en: spec.classification };
  const S = STRINGS[lang];
  return {
    lang,
    rtl: lang === "ar",
    S,
    title: t(spec.title, lang),
    subtitle: t(spec.subtitle, lang),
    year: spec.year ?? now.getFullYear(),
    classification: t(cls, lang),
    generatedBy: t(spec.generatedBy, lang) || "—",
    orgName: tokens.name[lang],
    dates: dates(now, lang),
    sections: (spec.sections || []).map((s) => ({ ...s, title: t(s.title, lang) })),
    t: (v) => t(v, lang),
    fmt: (v, col) => formatValue(v, col, lang),
  };
}

/** Computes a totals row for a table section (sums numeric columns). */
function totalsRow(section, lang) {
  if (!section.totals) return null;
  if (typeof section.totals === "object") return section.totals;
  const row = {};
  section.columns.forEach((col, i) => {
    if (i === 0) { row[col.key] = STRINGS[lang].total; return; }
    const nums = section.rows.map((r) => r[col.key]).filter((v) => typeof v === "number");
    row[col.key] = col.sum === false || nums.length === 0 || col.format === "percent" ? "" : nums.reduce((a, b) => a + b, 0);
  });
  return row;
}

const dataUri = (file, mime) => `data:${mime};base64,${readFileSync(file).toString("base64")}`;

